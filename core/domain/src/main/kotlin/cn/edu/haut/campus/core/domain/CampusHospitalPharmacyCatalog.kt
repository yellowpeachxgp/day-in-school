package cn.edu.haut.campus.core.domain

enum class HospitalMedicineCategory(val label: String) {
    WESTERN("西药/化学药"),
    TRADITIONAL_CHINESE("中成药"),
    BIOLOGICAL("生物制品")
}

data class HospitalMedicineDisclosureItem(
    val id: String,
    val name: String,
    val specification: String,
    val dosageForm: String,
    val unit: String,
    val disclosedPriceYuan: String,
    val manufacturer: String,
    val approvalNumber: String,
    val sourcePage: Int,
    val capturedDateIso: String = "2026-06-23",
    val contributorHandle: String = "Lollipop2233",
    val contributorGithubUrl: String = "https://github.com/Lollipop2233",
    val verificationStatus: String = "VERIFIED"
) {
    val category: HospitalMedicineCategory
        get() = when {
            approvalNumber.contains("Z", ignoreCase = true) -> HospitalMedicineCategory.TRADITIONAL_CHINESE
            approvalNumber.contains("S", ignoreCase = true) -> HospitalMedicineCategory.BIOLOGICAL
            else -> HospitalMedicineCategory.WESTERN
        }
}

