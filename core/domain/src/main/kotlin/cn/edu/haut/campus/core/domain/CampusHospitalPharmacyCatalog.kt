    fun search(
        query: String,
        categoryFilter: HospitalMedicineCategory? = null,
        dosageFormFilter: String? = null
    ): List<HospitalMedicineDisclosureItem> {
        val q = query.trim().lowercase()
        return ITEMS.filter { item ->
            val catOk = categoryFilter == null || item.category == categoryFilter
            val formOk = dosageFormFilter.isNullOrBlank() || item.dosageForm.contains(dosageFormFilter)
            val textOk = q.isEmpty() ||
                item.name.lowercase().contains(q) ||
                item.specification.lowercase().contains(q) ||
                item.dosageForm.lowercase().contains(q) ||
                item.manufacturer.lowercase().contains(q) ||
                item.approvalNumber.lowercase().contains(q)
            catOk && formOk && textOk
        }
    }
